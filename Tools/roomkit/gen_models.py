r"""Write IndevScpModels.bb from scp_models.py: which SCPs of the containment blocks get a real mesh or a figure.
The placing code is in IndevScpProps.bb.
   python gen_models.py"""
import os
from scp_models import MESHES, NPCS

ROOT = r'I:\MythicalC v1.2.7\v0.1\scpcb-dx9\scpcb-dx9'


def main():
    out = [';generated by Tools' + chr(92) + 'roomkit' + chr(92) + 'gen_models.py from scp_models.py - do not edit', '',
           ';the mesh of SCP n: its file, height (room units), base above the floor, and offset towards the far wall',
           'Function IndevScpMeshFile$(n$)', '\tSelect n']
    for n, (f, h, y, x) in sorted(MESHES.items()):
        out.append('\t\tCase "%s" : Return "%s"' % (n, f))
    out += ['\tEnd Select', '\tReturn ""', 'End Function', '', 'Function IndevScpMeshDims$(n$)', '\tSelect n']
    for n, (f, h, y, x) in sorted(MESHES.items()):
        out.append('\t\tCase "%s" : Return "%d|%d|%d"' % (n, h, y, x))
    out += ['\tEnd Select', '\tReturn ""', 'End Function', '',
            ';the skin of SCP n when it is a figure standing in its cell ("" = not a figure)', 'Function IndevScpNPCSkin$(n$)', '\tSelect n']
    for n, s in sorted(NPCS.items()):
        out.append('\t\tCase "%s" : Return "%s"' % (n, s))
    out += ['\tEnd Select', '\tReturn ""', 'End Function', '']
    open(os.path.join(ROOT, 'IndevScpModels.bb'), 'w', newline='\r\n').write('\n'.join(out))
    print('IndevScpModels.bb: %d meshes, %d figures' % (len(MESHES), len(NPCS)))


if __name__ == '__main__':
    main()
