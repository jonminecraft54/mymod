"""Build the ten rooms of the seventh batch (10 SCPs) and write everything derived from them:
     GFX\\map\\<room>.rmesh + _lm1.png        (with --game, otherwise into out\\)
     IndevS10Data.bb                           generated: S10_* slot constants, FillRoom table, fans, events
     b7_rooms.ini.txt / b7_names.txt           what wire7.py appends to Data\\rooms.ini and hooks into FillRoom
     previews\\annex_rooms_b7.jpg              one render + one plan per room
   python gen_b7.py --game            everything
   python gen_b7.py room2diner        one room into out\\ with a plan view
Same table format as gen_s16.blitz(), plus doors that can start open or use the old Indev panel."""
import os
import sys
import time
from PIL import Image, ImageDraw, ImageFont
import roomkit
import rooms_b7
from gen_s16 import f, ROOT

P, FNAME, EVENT = 'S10', 'IndevS10Data.bb', 's10room'


def blitz(rooms, P='S10', FNAME='IndevS10Data.bb', EVENT='s10room', gen='gen_b7.py', src='rooms_b7.py',
          what='The ten rooms of the seventh batch (10 SCPs)'):
    consts, fill, spin = [], [], []
    for R, key, desc, zone, pos, view in rooms:
        slot = dslot = 0
        if any(s['kind'] == 'lift' for s in R.spawns):
            slot = dslot = 2
        L, S, nfan = [], [], 0
        for s in R.spawns:
            k = s['kind']
            if 'pos' in s:
                x, y, z = s['pos']
            if k == 'item':
                L.append('IV1Item(r, "%s", %s, %s, %s, %d)' % (s['name'], f(x), f(y), f(z), s['chance']))
            elif k == 'door':
                L.append('IV1Door(r, %s, %s, %s, %d, %d)' % (f(x), f(y), f(z), s['angle'], s['key']))
            elif k == 'ndoor':
                tf = lambda v: 'True' if v else 'False'
                L.append('r\\RoomDoors[%d] = IS10Door(r, %s, %s, %s, %d, %d, %s, %s, %s)' % (
                    dslot, f(x), f(y), f(z), s['angle'], s['key'], tf(s['locked']), tf(s.get('open')), tf(s.get('old'))))
                consts.append(('%s_%s_D_%s' % (P, key, s['name']), dslot))
                dslot += 1
            elif k == 'named':
                L.append('r\\Objects[%d] = IAxPivot(r, %s, %s, %s)' % (slot, f(x), f(y), f(z)))
                consts.append(('%s_%s_%s' % (P, key, s['name']), slot))
                slot += 1
            elif k == 'reserve':
                consts.append(('%s_%s_%s' % (P, key, s['name']), slot))
                slot += s['n']
            elif k in ('fan', 'ceilfan', 'bigfan'):
                if k == 'fan':
                    L.append('r\\Objects[%d] = IAxFan(r, "GFX\\map\\indev_fan.b3d", %s, %s, %s, %s, %d)' % (slot, f(x), f(y), f(z), f(s['radius']), s['yaw']))
                    S.append('TurnEntity(r\\Objects[%d], 0, 0, 5.0 * k * FPSfactor)' % slot)
                elif k == 'ceilfan':
                    L.append('r\\Objects[%d] = IAxFan(r, "GFX\\map\\indev_ceilfan.b3d", %s, %s, %s, %s, 0)' % (slot, f(x), f(y), f(z), f(s['radius'])))
                    S.append('TurnEntity(r\\Objects[%d], 0, 2.0 * k * FPSfactor, 0)' % slot)
                else:
                    L.append('r\\Objects[%d] = IAxFan(r, "GFX\\map\\indev_fan.b3d", %s, %s, %s, %s, 0)' % (slot, f(x), f(y), f(z), f(s['radius'])))
                    L.append('RotateEntity(r\\Objects[%d], 90, 0, 0)' % slot)
                    S.append('TurnEntity(r\\Objects[%d], 0, 0, 3.5 * k * FPSfactor)' % slot)
                consts.append(('%s_%s_FAN%d' % (P, key, nfan), slot))
                nfan += 1
                slot += 1
            elif k == 'lever':
                L.append('IAxLever(r, %d, %s, %s, %s, %d, %s)' % (slot, f(x), f(y), f(z), s['yaw'], 'True' if s['up'] else 'False'))
                consts.append(('%s_%s_%s' % (P, key, s['name']), slot))
                slot += 2
            elif k == 'lift':
                a, ap, b, bp = s['a'], s['ap'], s['b'], s['bp']
                L.append('IAxElevator(r, ' + ', '.join(f(v) for v in (list(a) + list(ap) + list(b) + list(bp))) + ')')
            else:
                raise ValueError(k)
        assert slot <= 30 and dslot <= 8, (R.name, slot, dslot)
        consts.append(('%s_%s_SLOTS' % (P, key), slot))
        fill.append((R.name, L))
        if S:
            spin.append((R.name, S))
    names = [c[0] for c in consts]
    assert len(names) == len(set(names)), 'duplicate slot name'
    out = [';=====================================================================',
           '; GENERATED by Tools\\roomkit\\%s from %s - edit the Python, not this file.' % (gen, src),
           '; %s: which r\\Objects[] / r\\RoomDoors[] slot holds what,' % what,
           '; and what each room needs created when the map is built. Lift rooms keep 0 / 1 for the lift.',
           ';=====================================================================', '']
    for n, v in consts:
        out.append('Const %s%% = %d' % (n, v))
    out += ['', 'Function IndevFill%s(r.Rooms)' % P, '\tSelect r\\RoomTemplate\\Name']
    for name, L in fill:
        out.append('\t\tCase "%s"' % name)
        out += ['\t\t\t' + l for l in L]
    out += ['\tEnd Select', '\tIndev%sDress(r) ;the things only the code can make (Indev%s.bb)' % (P, P), 'End Function', '',
            ';every fan in these rooms; k = speed (1 = idling)', 'Function Indev%sSpin(r.Rooms, k#)' % P, '\tSelect r\\RoomTemplate\\Name']
    for name, S in spin:
        out.append('\t\tCase "%s"' % name)
        out += ['\t\t\t' + l for l in S]
    out += ['\tEnd Select', 'End Function', '', 'Function Indev%sEvents()' % P]
    for name, _ in fill:
        out.append('\tCreateEvent("%s", "%s", 0, 1.0)' % (EVENT, name))
    out += ['End Function', '']
    open(os.path.join(ROOT, FNAME), 'wb').write('\r\n'.join(out).encode('latin-1'))


def ini(rooms):
    out = ['', ';INDEV SEVENTH BATCH - 10 SCPs (generated meshes, Tools\\roomkit\\gen_b7.py, IndevS10.bb)',
           ';=================================================']
    for R, key, desc, zone, pos, view in rooms:
        out += ['', '[%s]' % R.name, 'descr=%s' % desc, 'mesh path=GFX\\map\\%s.rmesh' % R.name, 'shape = 2',
                'commonness = 0', 'disabledecals = true', 'zone1=%d' % zone, 'set room=%s' % pos, 'set room priority=12000']
    open('b7_rooms.ini.txt', 'w').write('\n'.join(out) + '\n')
    open('b7_names.txt', 'w').write('\n'.join(R.name for R, *_ in rooms) + '\n')


if __name__ == '__main__':
    game = '--game' in sys.argv
    only = [a for a in sys.argv[1:] if not a.startswith('--')]
    outdir = roomkit.MAPDIR if game else 'out'
    os.makedirs('out', exist_ok=True)
    t0 = time.time()
    built = []
    for fn in rooms_b7.ALL:
        if only and fn.__name__ not in only:
            continue
        ret = fn()
        R = ret[0]
        assert R.name == fn.__name__, (R.name, fn.__name__)
        R.bake(verbose=False)
        R.export(outdir)
        R.render(ret[5][0], ret[5][1], 'out/b7_%s.png' % R.name, size=(768, 432))
        y = ret[5][0][1]
        R.topview('out/b7_%s_top.png' % R.name, y_cut=(y - 400, y + 100) if y < 0 or y > 600 else None)
        built.append(ret)
        print('  %s  %d surfaces  %.0fs' % (R.name, len(R.surfs), time.time() - t0))
    if not only:
        blitz(built)
        ini(built)
        tw, th = 512, 288
        cols = 5
        rows = (len(built) + cols - 1) // cols
        sheet = Image.new('RGB', (tw * cols, (th + 22) * 2 * rows), (16, 16, 18))
        d = ImageDraw.Draw(sheet)
        font = ImageFont.truetype(r"C:\Windows\Fonts\arialbd.ttf", 15)
        for i, (R, key, desc, zone, pos, view) in enumerate(built):
            x, y = (i % cols) * tw, (i // cols) * (th + 22) * 2
            sheet.paste(Image.open('out/b7_%s.png' % R.name).resize((tw, th), Image.LANCZOS), (x, y + 22))
            top = Image.open('out/b7_%s_top.png' % R.name).convert('RGB')
            top.thumbnail((tw, th), Image.LANCZOS)
            sheet.paste(top, (x + (tw - top.width) // 2, y + th + 44))
            d.text((x + 5, y + 3), '%s (zone %d)' % (R.name, zone), font=font, fill=(235, 220, 120))
        os.makedirs('previews', exist_ok=True)
        sheet.save('previews/annex_rooms_b7.jpg', quality=86)
    print('%d rooms in %.1fs -> %s' % (len(built), time.time() - t0, outdir))
