"""Build the six rooms of the twenty-fourth batch (25 SCPs) and write everything derived from them:
     GFX\\map\\<room>.rmesh + _lm1.png        (with --game, otherwise into out\\)
     IndevU24Data.bb                           generated: U24_* slot constants, FillRoom table, events
     b24_rooms.ini.txt / b24_names.txt         what wire18.py appends to Data\\rooms.ini and hooks into FillRoom
     previews\\annex_rooms_b24.jpg             one render + one plan per room
   python gen_b24.py --game            everything
   python gen_b24.py room2doorhall     one room into out\\ with a plan view

Lightmaps are capped at 2048 x 2048 (LM_MAX) so the new rooms stay inside the GPU memory budget."""
import os
import sys
import time
from PIL import Image, ImageDraw, ImageFont
import roomkit
import rooms_b24
from gen_b7 import blitz

LM_MAX = 2048


def ini(rooms):
    out = ['', ';INDEV TWENTY-FOURTH BATCH - 25 SCPs, four blocks and Storage 6H (generated, Tools\\roomkit\\gen_b24.py, IndevU24.bb)',
           ';=================================================']
    for R, key, desc, zone, pos, view in rooms:
        out += ['', '[%s]' % R.name, 'descr=%s' % desc, 'mesh path=GFX\\map\\%s.rmesh' % R.name, 'shape = 2',
                'commonness = 0', 'disabledecals = true', 'zone1=%d' % zone, 'set room=%s' % pos, 'set room priority=9000']
    open('b24_rooms.ini.txt', 'w').write('\n'.join(out) + '\n')
    open('b24_names.txt', 'w').write('\n'.join(R.name for R, *_ in rooms) + '\n')


if __name__ == '__main__':
    game = '--game' in sys.argv
    only = [a for a in sys.argv[1:] if not a.startswith('--')]
    outdir = roomkit.MAPDIR if game else 'out'
    os.makedirs('out', exist_ok=True)
    t0 = time.time()
    built = []
    for fn in rooms_b24.ALL:
        if only and fn.__name__ not in only:
            continue
        ret = fn()
        R = ret[0]
        assert R.name == fn.__name__, (R.name, fn.__name__)
        R.bake(verbose=False, max_size=LM_MAX)
        R.export(outdir)
        R.render(ret[5][0], ret[5][1], 'out/b24_%s.png' % R.name, size=(768, 432))
        y = ret[5][0][1]
        R.topview('out/b24_%s_top.png' % R.name, y_cut=(y - 400, y + 100) if y < 0 or y > 600 else None)
        built.append(ret)
        print('  %s  %d surfaces  lightmap %d  %.0fs' % (R.name, len(R.surfs), R.atlas_size, time.time() - t0))
    if not only:
        blitz(built, P='U24', FNAME='IndevU24Data.bb', EVENT='u24room', gen='gen_b24.py', src='rooms_b24.py',
              what='The six rooms of the twenty-fourth batch (25 SCPs)')
        ini(built)
        tw, th = 512, 288
        cols = 3
        rows = (len(built) + cols - 1) // cols
        sheet = Image.new('RGB', (tw * cols, (th + 22) * rows), (16, 16, 18))
        d = ImageDraw.Draw(sheet)
        font = ImageFont.truetype(r"C:\Windows\Fonts\arialbd.ttf", 15)
        for i, (R, key, desc, zone, pos, view) in enumerate(built):
            x, y0 = (i % cols) * tw, (i // cols) * (th + 22)
            sheet.paste(Image.open('out/b24_%s.png' % R.name).resize((tw, th), Image.LANCZOS), (x, y0 + 22))
            d.text((x + 5, y0 + 3), '%s (zone %d)' % (R.name, zone), font=font, fill=(235, 220, 120))
        os.makedirs('previews', exist_ok=True)
        sheet.save('previews/annex_rooms_b24.jpg', quality=86)
    print('%d rooms in %.1fs -> %s' % (len(built), time.time() - t0, outdir))



def table():
    """IndevU24Table.bb: what each SCP of scps_b24.py does when clicked or approached (IndevU24.bb calls it)"""
    from scps_b24 import SCPS
    q = lambda s: s.replace('"', "'")
    out = [';generated by Tools' + chr(92) + 'roomkit' + chr(92) + 'gen_b24.py from scps_b24.py - do not edit', '',
           ';the effect of clicking SCP n (its pivot p); isnew is True the first time', 'Function IndevU24Click(n$, p%, isnew%)',
           '\tSelect n']
    near = ['', ';the message shown once when you first come close to SCP n ("" for none)', 'Function IndevU24Near$(n$)',
            '\tSelect n']
    for n, cls, kind, col, desc, cont, rem, msg, fx in SCPS:
        out.append('\t\tCase "%s"' % n)
        body = []
        if fx.get('once'):
            body.append('If Not isnew Then IS16Tell("Nothing more happens.", 3) : Return')
        if 'stress' in fx:
            body.append('IndevStress = IndevStress + %d' % fx['stress'])
        if 'inj' in fx:
            body.append('Injuries = Injuries + %.2f' % fx['inj'])
        if 'stam' in fx:
            body.append('Stamina = %d' % fx['stam'])
        if 'blur' in fx:
            body.append('BlurTimer = %d' % fx['blur'])
        if 'give' in fx:
            body.append('IS16Give("%s", p)' % fx['give'])
        if 'sound' in fx:
            body.append('IS10Sound("SFX\Indev\%s.wav", p, 6.0, 0.8)' % fx['sound'])
        body.append('IS16Tell("%s", 7)' % q(msg))
        out += ['\t\t\t' + b for b in body]
        if 'near' in fx:
            near += ['\t\tCase "%s"' % n, '\t\t\tReturn "%s"' % q(fx['near'])]
    out += ['\tEnd Select', 'End Function']
    near += ['\tEnd Select', '\tReturn ""', 'End Function', '']
    open(os.path.join(roomkit.ROOT if hasattr(roomkit, 'ROOT') else r'I:\MythicalC v1.2.7\v0.1\scpcb-dx9\scpcb-dx9', 'IndevU24Table.bb'),
         'w', newline='\r\n').write('\n'.join(out + near))


if __name__ == '__main__' and '--game' in sys.argv:
    table()
    print('IndevU24Table.bb written')
