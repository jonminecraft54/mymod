"""Build the 24 v0.1-style rooms, and write everything derived from them:
     GFX\\map\\<room>.rmesh + _lm1.png        (with --game, otherwise into out\\)
     IndevV01Data.bb                           the generated FillRoom table + event list
     v01_rooms.ini.txt / v01_names.txt         what wire3.py appends to Data\\rooms.ini and hooks into FillRoom
     previews\\annex_rooms_v01.jpg             one render per room
   python gen_v01.py --game            everything
   python gen_v01.py room2v_arch       one room into out\\ with a preview"""
import os
import sys
import time
from PIL import Image, ImageDraw, ImageFont
import roomkit
import rooms_v01

ROOT = r"I:\MythicalC v1.2.7\v0.1\scpcb-dx9\scpcb-dx9"


def f(v):
    return '%.1f' % float(v)


def blitz(rooms):
    L = [';=====================================================================',
         '; GENERATED by Tools\\roomkit\\gen_v01.py from rooms_v01.py - edit the Python, not this file.',
         '; What each v0.1-style room needs created at map build: items, doors, fans, lift, NPC spot.',
         ';   Objects[0..1] lift pivots, [2] duct fan, [3] ceiling fan, [4] where the NPC of the room is',
         ';=====================================================================', '',
         'Function IndevFillV01(r.Rooms)', '\tSelect r\\RoomTemplate\\Name']
    for R, desc, shape, common, view in rooms:
        L.append('\t\tCase "%s"' % R.name)
        for s in R.spawns:
            k = s['kind']
            if k == 'item':
                x, y, z = s['pos']
                L.append('\t\t\tIV1Item(r, "%s", %s, %s, %s, %d)' % (s['name'], f(x), f(y), f(z), s['chance']))
            elif k == 'door':
                x, y, z = s['pos']
                L.append('\t\t\tIV1Door(r, %s, %s, %s, %d, %d)' % (f(x), f(y), f(z), s['angle'], s['key']))
            elif k == 'fan':
                x, y, z = s['pos']
                L.append('\t\t\tr\\Objects[2] = IAxFan(r, "GFX\\map\\indev_fan.b3d", %s, %s, %s, %s, %d)' % (f(x), f(y), f(z), f(s['radius']), s['yaw']))
            elif k == 'ceilfan':
                x, y, z = s['pos']
                L.append('\t\t\tr\\Objects[3] = IAxFan(r, "GFX\\map\\indev_ceilfan.b3d", %s, %s, %s, %s, 0)' % (f(x), f(y), f(z), f(s['radius'])))
            elif k == 'spot':
                x, y, z = s['pos']
                L.append('\t\t\tr\\Objects[4] = IAxPivot(r, %s, %s, %s)' % (f(x), f(y), f(z)))
            elif k == 'lift':
                a, ap, b, bp = s['a'], s['ap'], s['b'], s['bp']
                L.append('\t\t\tIAxElevator(r, ' + ', '.join(f(v) for v in (list(a) + list(ap) + list(b) + list(bp))) + ')')
    L += ['\tEnd Select', 'End Function', '', 'Function IndevV01Events()']
    for R, desc, shape, common, view in rooms:
        L.append('\tCreateEvent("v01room", "%s", 0, 1.0)' % R.name)
    L += ['End Function', '']
    open(os.path.join(ROOT, 'IndevV01Data.bb'), 'wb').write('\r\n'.join(L).encode('latin-1'))


def ini(rooms):
    out = ['', ';INDEV v0.1-STYLE FILLER ROOMS (generated meshes, Tools\\roomkit\\gen_v01.py, IndevV01.bb)',
           ';=================================================']
    for R, desc, shape, common, view in rooms:
        out += ['', '[%s]' % R.name, 'descr=%s' % desc, 'mesh path=GFX\\map\\%s.rmesh' % R.name, 'shape = %s' % shape,
                'commonness = %d' % common, 'disabledecals = true', 'zone1=4']
    open('v01_rooms.ini.txt', 'w').write('\n'.join(out) + '\n')
    open('v01_names.txt', 'w').write('\n'.join(R.name for R, *_ in rooms) + '\n')


if __name__ == '__main__':
    game = '--game' in sys.argv
    only = [a for a in sys.argv[1:] if not a.startswith('--')]
    outdir = roomkit.MAPDIR if game else 'out'
    os.makedirs('out', exist_ok=True)
    t0 = time.time()
    built = []
    for fn in rooms_v01.ALL:
        if only and fn.__name__ not in only:
            continue
        R, desc, shape, common, view = fn()
        R.bake(verbose=False)
        R.export(outdir)
        R.render(view[0], view[1], 'out/v01_%s.png' % R.name, size=(640, 360))
        if only:
            R.topview('out/v01_%s_top.png' % R.name)
        built.append((R, desc, shape, common, view))
    if not only:
        blitz(built)
        ini(built)
        tw, th = 480, 270
        cols = 4
        rows = (len(built) + cols - 1) // cols
        sheet = Image.new('RGB', (tw * cols, (th + 24) * rows), (16, 16, 18))
        d = ImageDraw.Draw(sheet)
        font = ImageFont.truetype(r"C:\Windows\Fonts\arialbd.ttf", 15)
        for i, (R, desc, shape, common, view) in enumerate(built):
            im = Image.open('out/v01_%s.png' % R.name).resize((tw, th), Image.LANCZOS)
            x, y = (i % cols) * tw, (i // cols) * (th + 24)
            sheet.paste(im, (x, y + 24))
            d.text((x + 6, y + 4), '%s  (shape %s)' % (R.name, shape), font=font, fill=(235, 220, 120))
        os.makedirs('previews', exist_ok=True)
        sheet.save('previews/annex_rooms_v01.jpg', quality=86)
    print('%d rooms in %.1fs -> %s' % (len(built), time.time() - t0, outdir))
