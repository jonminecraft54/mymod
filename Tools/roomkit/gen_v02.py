"""Build the 55 "w series" v0.1-style rooms and write everything derived from them:
     GFX\\map\\<room>.rmesh + _lm1.png        (with --game, otherwise into out\\)
     IndevV02Data.bb                           generated: FillRoom table, event list, NPC roles, rare-item tags
     v02_rooms.ini.txt / v02_names.txt         what wire4.py appends to Data\\rooms.ini and hooks into FillRoom
     previews\\annex_rooms_v02.jpg             one render per room
   python gen_v02.py --game            everything
   python gen_v02.py room2w_mezz       one room into out\\ with a plan view"""
import os
import sys
import time
from PIL import Image, ImageDraw, ImageFont
import roomkit
import rooms_v02

ROOT = r"I:\MythicalC v1.2.7\v0.1\scpcb-dx9\scpcb-dx9"


def f(v):
    return '%.1f' % float(v)


def blitz(rooms):
    L = [';=====================================================================',
         '; GENERATED by Tools\\roomkit\\gen_v02.py from rooms_v02.py - edit the Python, not this file.',
         '; The 55 "w series" v0.1-style rooms: what each needs created when the map is built.',
         ';   Objects[0..1] lift pivots, [2] duct fan, [3] ceiling fan, [4] NPC spot, [5] big extractor fan',
         ';=====================================================================', '',
         'Function IndevFillV02(r.Rooms)', '\tSelect r\\RoomTemplate\\Name']
    roles, yaws, tags = [], [], []
    for R, desc, shape, common, view, tag in rooms:
        L.append('\t\tCase "%s"' % R.name)
        if tag:
            tags.append((R.name, tag))
        for s in R.spawns:
            k = s['kind']
            if k in ('item', 'door', 'fan', 'ceilfan', 'spot', 'roll', 'bigfan'):
                x, y, z = s['pos']
            if k == 'item':
                L.append('\t\t\tIV1Item(r, "%s", %s, %s, %s, %d)' % (s['name'], f(x), f(y), f(z), s['chance']))
            elif k == 'door':
                L.append('\t\t\tIV1Door(r, %s, %s, %s, %d, %d)' % (f(x), f(y), f(z), s['angle'], s['key']))
            elif k == 'fan':
                L.append('\t\t\tr\\Objects[2] = IAxFan(r, "GFX\\map\\indev_fan.b3d", %s, %s, %s, %s, %d)' % (f(x), f(y), f(z), f(s['radius']), s['yaw']))
            elif k == 'ceilfan':
                L.append('\t\t\tr\\Objects[3] = IAxFan(r, "GFX\\map\\indev_ceilfan.b3d", %s, %s, %s, %s, 0)' % (f(x), f(y), f(z), f(s['radius'])))
            elif k == 'bigfan':
                L.append('\t\t\tr\\Objects[5] = IAxFan(r, "GFX\\map\\indev_fan.b3d", %s, %s, %s, %s, 0)' % (f(x), f(y), f(z), f(s['radius'])))
                L.append('\t\t\tRotateEntity(r\\Objects[5], 90, 0, 0)')
            elif k == 'spot':
                L.append('\t\t\tr\\Objects[4] = IAxPivot(r, %s, %s, %s)' % (f(x), f(y), f(z)))
                roles.append((R.name, s.get('role', '')))
                yaws.append((R.name, int(s.get('yaw', 0))))
            elif k == 'roll':
                L.append('\t\t\tIndevRoll(r, r\\x + %s * RoomScale, r\\y + %s * RoomScale, r\\z + %s * RoomScale)' % (f(x), f(y + 16), f(z)))
            elif k == 'lift':
                a, ap, b, bp = s['a'], s['ap'], s['b'], s['bp']
                L.append('\t\t\tIAxElevator(r, ' + ', '.join(f(v) for v in (list(a) + list(ap) + list(b) + list(bp))) + ')')
    L += ['\tEnd Select', 'End Function', '', 'Function IndevV02Events()']
    for R, *_ in rooms:
        L.append('\tCreateEvent("v02room", "%s", 0, 1.0)' % R.name)
    L += ['End Function', '', ';which NPC a room has (see UpdateIndevV02)', 'Function IndevV02Role$(n$)', '\tSelect n']
    for name, role in roles:
        L.append('\t\tCase "%s" Return "%s"' % (name, role))
    L += ['\tEnd Select', '\tReturn ""', 'End Function', '', ';the way that NPC faces, relative to the room', 'Function IndevV02Yaw%(n$)', '\tSelect n']
    for name, yaw in yaws:
        L.append('\t\tCase "%s" Return %d' % (name, yaw))
    L += ['\tEnd Select', '\tReturn 0', 'End Function', '',
          ';rare-item category of a room (IndevRoomTag in IndevRareSpawn.bb falls back to this)',
          'Function IndevV02Tag$(n$)', '\tSelect n']
    by = {}
    for name, tag in tags:
        by.setdefault(tag, []).append(name)
    for tag, names in by.items():
        L.append('\t\tCase %s Return "%s"' % (', '.join('"%s"' % n for n in names), tag))
    L += ['\tEnd Select', '\tReturn ""', 'End Function', '']
    open(os.path.join(ROOT, 'IndevV02Data.bb'), 'wb').write('\r\n'.join(L).encode('latin-1'))


def ini(rooms):
    out = ['', ';INDEV v0.1-STYLE FILLER ROOMS, "w" SERIES (generated meshes, Tools\\roomkit\\gen_v02.py, IndevV02.bb)',
           ';=================================================']
    for R, desc, shape, common, view, tag in rooms:
        out += ['', '[%s]' % R.name, 'descr=%s' % desc, 'mesh path=GFX\\map\\%s.rmesh' % R.name, 'shape = %s' % shape,
                'commonness = %d' % common, 'disabledecals = true', 'zone1=4']
    open('v02_rooms.ini.txt', 'w').write('\n'.join(out) + '\n')
    open('v02_names.txt', 'w').write('\n'.join(R.name for R, *_ in rooms) + '\n')


if __name__ == '__main__':
    game = '--game' in sys.argv
    only = [a for a in sys.argv[1:] if not a.startswith('--')]
    outdir = roomkit.MAPDIR if game else 'out'
    os.makedirs('out', exist_ok=True)
    t0 = time.time()
    built = []
    for fn in rooms_v02.ALL:
        if only and fn.__name__ not in only:
            continue
        R, desc, shape, common, view, tag = fn()
        assert R.name == fn.__name__, (R.name, fn.__name__)
        R.bake(verbose=False)
        R.export(outdir)
        R.render(view[0], view[1], 'out/v02_%s.png' % R.name, size=(640, 360))
        if only:
            R.topview('out/v02_%s_top.png' % R.name)
        built.append((R, desc, shape, common, view, tag))
    if not only:
        blitz(built)
        ini(built)
        tw, th = 384, 216
        cols = 6
        rows = (len(built) + cols - 1) // cols
        sheet = Image.new('RGB', (tw * cols, (th + 22) * rows), (16, 16, 18))
        d = ImageDraw.Draw(sheet)
        font = ImageFont.truetype(r"C:\Windows\Fonts\arialbd.ttf", 14)
        for i, (R, desc, shape, common, view, tag) in enumerate(built):
            im = Image.open('out/v02_%s.png' % R.name).resize((tw, th), Image.LANCZOS)
            x, y = (i % cols) * tw, (i // cols) * (th + 22)
            sheet.paste(im, (x, y + 22))
            d.text((x + 5, y + 3), '%s (%s)' % (R.name, shape), font=font, fill=(235, 220, 120))
        os.makedirs('previews', exist_ok=True)
        sheet.save('previews/annex_rooms_v02.jpg', quality=86)
    print('%d rooms in %.1fs -> %s' % (len(built), time.time() - t0, outdir))
